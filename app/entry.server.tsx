import { PassThrough } from "node:stream";
import type { AppLoadContext, EntryContext } from "@remix-run/node";
import { createReadableStreamFromReadable } from "@remix-run/node";
import { RemixServer } from "@remix-run/react";
import { isbot } from "isbot";
import { renderToPipeableStream } from "react-dom/server";
import { addDocumentResponseHeaders } from "./shopify.server";

const ABORT_DELAY = 5_000;

export default function handleRequest(
  request: Request,
  responseStatusCode: number,
  responseHeaders: Headers,
  remixContext: EntryContext,
  _loadContext: AppLoadContext
) {
  // Add Shopify Document response headers (CSP, etc.)
  addDocumentResponseHeaders(request, responseHeaders);

  // Dynamic frame-ancestors to ensure Shopify embedded compliance
  const url = new URL(request.url);
  const shop = url.searchParams.get("shop");
  
  // App Store & BFS Compliance: Strip X-Frame-Options to prevent iframe denial
  responseHeaders.delete("X-Frame-Options");
  
  // Ensure Content-Security-Policy includes admin.shopify.com and specific shop
  const frameAncestors = shop
    ? `frame-ancestors https://admin.shopify.com https://${shop} https://*.myshopify.com;`
    : `frame-ancestors https://admin.shopify.com https://*.myshopify.com;`;
  
  const existingCsp = responseHeaders.get("Content-Security-Policy");
  if (!existingCsp) {
    responseHeaders.set("Content-Security-Policy", frameAncestors);
  } else if (!existingCsp.includes("frame-ancestors")) {
    responseHeaders.set("Content-Security-Policy", `${existingCsp} ${frameAncestors}`);
  }

  return isbot(request.headers.get("user-agent"))
    ? handleBotRequest(
        request,
        responseStatusCode,
        responseHeaders,
        remixContext
      )
    : handleBrowserRequest(
        request,
        responseStatusCode,
        responseHeaders,
        remixContext
      );
}

function handleBotRequest(
  request: Request,
  responseStatusCode: number,
  responseHeaders: Headers,
  remixContext: EntryContext
) {
  return new Promise((resolve, reject) => {
    let shellRendered = false;
    const { pipe, abort } = renderToPipeableStream(
      <RemixServer
        context={remixContext}
        url={request.url}
        abortDelay={ABORT_DELAY}
      />,
      {
        onAllReady() {
          shellRendered = true;
          const body = new PassThrough();
          const stream = createReadableStreamFromReadable(body);

          responseHeaders.set("Content-Type", "text/html");

          resolve(
            new Response(stream, {
              headers: responseHeaders,
              status: responseStatusCode,
            })
          );

          pipe(body);
        },
        onShellError(error: unknown) {
          reject(error);
        },
        onError(error: unknown) {
          responseStatusCode = 500;
          if (shellRendered) {
            console.error(error);
          }
        },
      }
    );

    setTimeout(abort, ABORT_DELAY);
  });
}

